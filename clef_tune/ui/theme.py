        block_shadow="none",
        block_radius="10px",
        block_label_text_color="*neutral_600",
        block_label_text_color_dark="*neutral_400",
        block_label_background_fill="transparent",
        block_label_background_fill_dark="transparent",
        block_title_text_weight="600",
